import assert from 'node:assert/strict';
import { loadCatalog, validateCatalog, selectGames } from './catalog.mjs';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
const catalog = await loadCatalog();
const context = { window: {} };
vm.runInNewContext(await readFile(new URL('../games.js', import.meta.url), 'utf8'), context);
assert.equal(JSON.stringify(context.window.MEDIAN_STUDIO), JSON.stringify(catalog));
assert.deepEqual(selectGames(catalog,'apps','com.mediangames.fenjoon').map(g=>g.id),['looti-war']);
assert.deepEqual(selectGames(catalog,'apps','com.MedianGames.LootiWar').map(g=>g.id),['fenjoon']);
assert.deepEqual(selectGames(catalog,'apps','unknown').map(g=>g.id),['fenjoon','looti-war']);
assert.equal(selectGames(catalog,'website').length,3);
const fixture = structuredClone(catalog);
const original = fixture.games[0];
original.releasedAt = '2026-01-01T00:00:00Z';
const other = {...structuredClone(original),id:'second',bundleIds:['test.second'],releasedAt:'2026-10-01T00:00:00Z'};
fixture.games.push(other);
original.promotion = {enabled:true,priority:10,startsAt:'2026-10-01T00:00:00Z',endsAt:'2026-11-01T00:00:00Z',apps:true,website:false,links:false};
assert.equal(selectGames(fixture,'apps','',new Date('2026-10-15T00:00:00Z'))[0].id,'fenjoon');
assert.equal(selectGames(fixture,'apps','',new Date('2026-11-01T00:00:00Z'))[0].id,'second');
assert.equal(selectGames(fixture,'website','',new Date('2026-10-15T00:00:00Z'))[0].id,'second');
fixture.games.push(structuredClone(other));
assert.throws(()=>validateCatalog(fixture),/Duplicate/);
const invalid=structuredClone(catalog); invalid.games[0].storeUrl='javascript:alert(1)';
assert.throws(()=>validateCatalog(invalid),/URL/);
assert.equal((await readFile(new URL('../dist/data/studio.v1.json',import.meta.url),'utf8')),await readFile(new URL('../data/studio.v1.json',import.meta.url),'utf8'));
console.log('Catalogue checks passed: generated data, publication, current/unknown game, concept filtering, promotion expiry/order, duplicates, HTTPS.');
